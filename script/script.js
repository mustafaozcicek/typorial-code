      // Special cleanup: some PDF-parsed glyph sets are incomplete/misaligned.
      // We use the nearest valid row count when a requested variant is unavailable.
      function normalizeRows(rows, targetRows) {
        if (!rows) return Array(targetRows).fill("000000000");
        if (rows.length === targetRows) return rows;
        if (rows.length > targetRows) return rows.slice(0, targetRows);
        const out = rows.slice();
        while (out.length < targetRows) {
          const insertAt = Math.max(1, out.length - 1);
          const source = out[Math.min(insertAt, out.length - 1)] || "000000000";
          out.splice(insertAt, 0, source);
        }
        return out.slice(0, targetRows);
      }

      function spiralPath(cols, rows = 3, startAtTop = false) {
        const path = [];
        let left = 0,
          right = cols - 1,
          top = 0,
          bottom = rows - 1;
        while (left <= right && top <= bottom) {
          // start lower-left and move upward on left edge
          for (let r = bottom; r >= top; r--) path.push([left, r]);
          left++;
          if (left > right || top > bottom) break;
          // across top
          for (let c = left; c <= right; c++) path.push([c, top]);
          top++;
          if (left > right || top > bottom) break;
          // down right edge
          for (let r = top; r <= bottom; r++) path.push([right, r]);
          right--;
          if (left > right || top > bottom) break;
          // across bottom
          for (let c = right; c >= left; c--) path.push([c, bottom]);
          bottom--;
        }
        return startAtTop
          ? path.map(([column, row]) => [column, rows - 1 - row])
          : path;
      }

      function snakePath(cols, rows = 3, startAtTop = false) {
        const path = [];
        for (let column = 0; column < cols; column++) {
          const topFirst = startAtTop
            ? column % 3 !== 2
            : column % 2 === 1;
          if (topFirst) {
            for (let row = 0; row < rows; row++) path.push([column, row]);
          } else {
            for (let row = rows - 1; row >= 0; row--) path.push([column, row]);
          }
        }
        return path;
      }

      function typesettingPath(cols, logic) {
        if (logic === "snake-lower") return snakePath(cols, 3, false);
        if (logic === "spiral-upper") return spiralPath(cols, 3, true);
        if (logic === "snake-upper") return snakePath(cols, 3, true);
        return spiralPath(cols, 3, false);
      }

      function latinFlowLayout(letterCount) {
        const cols = Math.floor(letterCount / 3) + 1;
        const grid = Array.from({ length: 3 }, () => Array(cols).fill(null));

        if (letterCount === 1) {
          grid[0][0] = 0;
          grid[1][0] = 0;
          grid[2][0] = 0;
        } else if (letterCount === 3) {
          grid[0] = [0, 1];
          grid[1] = [0, 2];
          grid[2] = [0, 2];
        } else {
          // The first letter always begins as a two-cell vertical stack.
          grid[0][0] = 0;
          grid[1][0] = 0;

          const reservedLetters = new Set([0]);
          if (letterCount % 3 === 0) {
            // Full groups get an extra column: first fills its column and the
            // final letter closes the far-right edge.
            grid[2][0] = 0;
            grid[1][cols - 1] = letterCount - 1;
            grid[2][cols - 1] = letterCount - 1;
            reservedLetters.add(letterCount - 1);
          } else if (letterCount % 3 === 1) {
            // Two spare cells enlarge both the opening and closing letters.
            grid[1][cols - 1] = letterCount - 1;
            grid[2][cols - 1] = letterCount - 1;
            reservedLetters.add(letterCount - 1);
          }

          let letterIndex = 1;
          for (let row = 0; row < 3; row++) {
            for (let column = 0; column < cols; column++) {
              if (grid[row][column] !== null) continue;
              while (reservedLetters.has(letterIndex)) letterIndex++;
              grid[row][column] = letterIndex++;
            }
          }
        }

        const path = [];
        const spans = [];
        for (let letterIndex = 0; letterIndex < letterCount; letterIndex++) {
          const cells = [];
          for (let row = 0; row < 3; row++) {
            for (let column = 0; column < cols; column++) {
              if (grid[row][column] === letterIndex) cells.push([column, row]);
            }
          }
          spans.push(cells.length);
          path.push(...cells);
        }

        return { path, spans };
      }

      // Allocate extra cells to the earliest vertical segments in any path.
      function allocateSpans(letterCount, path) {
        const spans = Array(letterCount).fill(1);
        const extra = path.length - letterCount;

        // The minimum 1-letter word fills the entire 3-cell column.
        if (letterCount === 1) {
          spans[0] = 3;
          return spans;
        }

        let remainingExtra = extra;
        if (remainingExtra >= 1) {
          spans[0] = remainingExtra >= 3 ? 3 : 2;
          remainingExtra -= spans[0] - 1;
        }

        if (remainingExtra >= 1) {
          let pathIndex = spans[0];
          for (let letterIndex = 1; letterIndex < letterCount; letterIndex++) {
            const current = path[pathIndex];
            const next = path[pathIndex + 1];
            if (
              current &&
              next &&
              current[0] === next[0] &&
              Math.abs(current[1] - next[1]) === 1
            ) {
              spans[letterIndex] = 2;
              remainingExtra--;
              pathIndex += 2;
              if (!remainingExtra) break;
              continue;
            }
            pathIndex++;
          }
        }

        return spans;
      }

      function glyphSVG(
        letter,
        span,
        scale,
        showPixels,
        pixelsToSet = [],
        horizontalCrop = null,
      ) {
        const targetRows = 9 * span;
        const source = normalizeRows(
          glyphs[letter]?.[span] || glyphs[letter]?.[1],
          targetRows,
        ).map((row) => [...row]);
        pixelsToSet.forEach(([row, column]) => {
          if (source[row]?.[column] !== undefined) source[row][column] = "1";
        });
        const viewX = horizontalCrop?.x ?? 0;
        const viewWidth = horizontalCrop?.width ?? 9;
        const w = viewWidth * scale,
          h = targetRows * scale;
        let svg = `<svg class="glyph" width="${w}" height="${h}" viewBox="${viewX} 0 ${viewWidth} ${targetRows}" xmlns="http://www.w3.org/2000/svg">`;
        if (showPixels) {
          for (let x = 0; x <= 9; x++)
            svg += `<line x1="${x}" y1="0" x2="${x}" y2="${targetRows}" stroke="var(--pixel-grid)" stroke-width="0.04"/>`;
          for (let y = 0; y <= targetRows; y++)
            svg += `<line x1="0" y1="${y}" x2="9" y2="${y}" stroke="var(--pixel-grid)" stroke-width="0.04"/>`;
        }
        source.forEach((row, y) => {
          row.forEach((v, x) => {
            if (v === "1")
              svg += `<rect class="pixel" x="${x}" y="${y}" width="1" height="1" fill="currentColor"/>`;
          });
        });
        svg += "</svg>";
        return svg;
      }

      function punctuationCrop(letter) {
        const rows = normalizeRows(glyphs[letter]?.[3] || glyphs[letter]?.[1], 27);
        let minX = 9;
        let maxX = -1;

        rows.forEach((row) => {
          [...row].forEach((value, column) => {
            if (value !== "1") return;
            minX = Math.min(minX, column);
            maxX = Math.max(maxX, column);
          });
        });

        if (maxX < minX) return { x: 0, width: 9 };
        const x = Math.max(0, minX - 1);
        const right = Math.min(9, maxX + 2);
        return { x, width: right - x };
      }

      function tokenizeText(text) {
        const tokens = [];
        let word = "";

        const commitWord = () => {
          if (word) tokens.push({ type: "word", value: word });
          word = "";
        };

        [...text].forEach((character) => {
          const glyphCharacter = character === "’" ? "'" : character;

          // Apostrophes belong to the word's spiral (Jack's, don't, James').
          if (/[A-Za-z0-9']/.test(glyphCharacter) && glyphs[glyphCharacter]) {
            word += character;
            return;
          }

          commitWord();
          if (character === "\r") return;
          if (character === "\n") {
            tokens.push({ type: "break" });
          } else if (character === "\t") {
            tokens.push({ type: "space", size: 4 });
          } else if (/\s/.test(character)) {
            tokens.push({ type: "space", size: 1 });
          } else if (glyphs[glyphCharacter]) {
            tokens.push({ type: "punctuation", value: glyphCharacter });
          }
        });

        commitWord();
        return tokens;
      }

