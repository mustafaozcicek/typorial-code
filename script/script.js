      function focusCanvas() {
        keyboardCapture.focus({ preventScroll: true });
      }

      function commitCapturedText() {
        if (!keyboardCapture.value) return;
        appendCanvasText(keyboardCapture.value);
        keyboardCapture.value = "";
      }

      function appendCanvasText(text) {
        if (replaceAllOnInput) canvasText = "";
        canvasText += text;
        replaceAllOnInput = false;
        render();
      }

      stage.addEventListener("pointerdown", (event) => {
        if (event.target.closest(".words, .stage")) focusCanvas();
      });

      keyboardCapture.addEventListener("compositionstart", () => {
        isComposing = true;
      });

      keyboardCapture.addEventListener("compositionend", () => {
        isComposing = false;
        requestAnimationFrame(commitCapturedText);
      });

      keyboardCapture.addEventListener("input", () => {
        if (!isComposing) commitCapturedText();
      });

      document.addEventListener("keydown", (event) => {
        if (isComposing || event.isComposing) return;

        const isCanvasTarget =
          event.target === keyboardCapture ||
          event.target === document.body ||
          event.target === document.documentElement ||
          stage.contains(event.target);
        if (!isCanvasTarget) return;

        if ((event.metaKey || event.ctrlKey) && event.key.toLowerCase() === "a") {
          event.preventDefault();
          replaceAllOnInput = true;
          return;
        }

        if (event.key === "Backspace" || event.key === "Delete") {
          event.preventDefault();
          canvasText = replaceAllOnInput ? "" : [...canvasText].slice(0, -1).join("");
          replaceAllOnInput = false;
          render();
          return;
        }

        if (event.key === "Enter") {
          event.preventDefault();
          appendCanvasText("\n");
          return;
        }

        if (
          event.key.length === 1 &&
          !event.metaKey &&
          !event.ctrlKey &&
          !event.altKey
        ) {
          event.preventDefault();
          appendCanvasText(event.key);
        }
      });

      document.addEventListener("paste", (event) => {
        const isCanvasTarget =
          event.target === keyboardCapture ||
          event.target === document.body ||
          stage.contains(event.target);
        if (!isCanvasTarget) return;

        const pastedText = event.clipboardData?.getData("text");
        if (!pastedText) return;
        event.preventDefault();
        appendCanvasText(pastedText);
      });

